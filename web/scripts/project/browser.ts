import assert from "node:assert/strict";
import { Notes } from "../../src/names";
const store = new Map<string, string>();
(globalThis as any).localStorage = { getItem: (k: string) => store.get(k) ?? null, setItem: (k: string, v: string) => store.set(k, v) };
const notes = new Notes(); notes.load("sample");
notes.setComment(0x1001, "checks configuration"); notes.toggleStar(0x1000); notes.rename(0x1000, "parse_config");
const reopened = new Notes(); reopened.load("sample");
assert.equal(reopened.commentAt(0x1001), "checks configuration");
assert.equal(reopened.comments(0x1001)[0].source, "human");
assert.equal(reopened.isStarred(0x1000), true);
assert.equal(reopened.renamed(0x1000), "parse_config");
assert.equal(reopened.canUndo(), false, "history stays in the session");
notes.undo(); notes.undo(); notes.undo();
assert.equal(notes.renamed(0x1000), undefined);
assert.equal(notes.isStarred(0x1000), false);
assert.equal(notes.commentAt(0x1001), undefined);
assert.equal(notes.canUndo(), false);
notes.setComment(0x1001, "sample comment"); notes.load("other");
assert.equal(notes.commentAt(0x1001), undefined);
assert.equal(notes.canUndo(), false, "switching samples resets undo");
(globalThis as any).localStorage = { getItem: () => { throw Error("blocked"); }, setItem: () => { throw Error("blocked"); } };
const blocked = new Notes(); blocked.load("blocked"); blocked.setComment(1, "local"); blocked.toggleStar(2);
assert.equal(blocked.commentAt(1), "local"); assert.equal(blocked.isStarred(2), true);
blocked.undo(); blocked.undo(); assert.equal(blocked.commentAt(1), undefined);
console.log("browser notes checks passed");
