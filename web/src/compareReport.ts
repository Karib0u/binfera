// A comparison as something to keep or send: Markdown, one HTML page, or the engine's own document as JSON.
import type { DiffDocument, FunctionMatch } from "./compare";
import { addressOf, changesOf, summaryOf } from "./compareModel";
import { htmlOf, markdownOf, type Block } from "./report";

const MAX_CHANGES = 500, MAX_ITEMS = 40;
const hex = (n: number) => "0x" + n.toString(16);
const size = (n: number) => (n > 1048576 ? (n / 1048576).toFixed(1) + " MB" : n > 1024 ? (n / 1024).toFixed(1) + " KB" : n + " B");
const pct = (v: number | null | undefined) => (v === null || v === undefined ? "n/a" : Math.round(v * 100) + "%");
const more = (items: string[], most = MAX_ITEMS) => [...items.slice(0, most), ...(items.length > most ? [`… and ${items.length - most} more`] : [])];

const TITLE = (d: DiffDocument) => `Comparison of ${d.inputs[0].name} and ${d.inputs[1].name}`;
const NOTE = "Generated by binfera from static analysis. Matches are the engine's best pairing of functions, with the evidence behind each; pairs made by hand are marked. A difference is a place to look, not a verdict.";

function blocks(d: DiffDocument, manual: FunctionMatch[]): Block[] {
  const [a, b] = d.inputs, summary = summaryOf(d), out: Block[] = [];
  out.push({ heading: "Summary", lines: [{ text: summary.headline }, ...summary.details.map((text) => ({ text }))] });
  out.push({
    heading: "Files",
    lines: [],
    table: {
      head: ["", "A", "B"],
      rows: [
        ["Name", a.name, b.name], ["Size", size(a.size), size(b.size)], ["SHA-256", a.sha256, b.sha256],
        ["Format", `${a.format} ${a.arch}`, `${b.format} ${b.arch}`], ["Functions", String(a.functions), String(b.functions)],
        ["Instructions", String(a.instructions), String(b.instructions)],
      ],
    },
  });
  const s = d.similarity;
  out.push({ heading: "Similarity", lines: [{ text: `Overall ${pct(s.overall)}` }, { text: `Code ${pct(s.code)} · Imports ${pct(s.imports)} · Strings ${pct(s.strings)} · Capabilities ${pct(s.capabilities)}` }] });
  if (d.warnings.length) out.push({ heading: "Warnings", lines: d.warnings.map((text) => ({ text })) });
  const cap = d.capability_delta;
  if (cap && (cap.added.length || cap.removed.length || cap.retargeted.length)) {
    out.push({
      heading: "Capabilities",
      lines: [
        ...(cap.added.length ? [{ text: `Only in B (${cap.added.length})`, sub: more(cap.added.map((r) => r.name + (r.attack.length ? ` [${r.attack.join(", ")}]` : ""))) }] : []),
        ...(cap.removed.length ? [{ text: `Only in A (${cap.removed.length})`, sub: more(cap.removed.map((r) => r.name + (r.attack.length ? ` [${r.attack.join(", ")}]` : ""))) }] : []),
        ...(cap.retargeted.length ? [{ text: `Moved to other functions (${cap.retargeted.length})`, sub: more(cap.retargeted.map((r) => r.name)) }] : []),
      ],
    });
  }
  const f = d.file_delta, fileLines: Block["lines"] = [];
  for (const [label, delta] of [["Sections", f.sections], ["Imports", f.imports], ["Exports", f.exports], ["Resources", f.resources]] as const) {
    if (!delta.added.length && !delta.removed.length && !delta.changed.length) continue;
    fileLines.push({
      text: label,
      sub: more([...delta.added.map((n) => `Added: ${n}`), ...delta.removed.map((n) => `Removed: ${n}`), ...delta.changed.map((c) => `Changed: ${c.name} (${c.changes.join("; ")})`)]),
    });
  }
  if (f.overlay.length) fileLines.push({ text: "Overlay", sub: f.overlay });
  if (f.imphash && f.imphash[0] !== f.imphash[1]) fileLines.push({ text: `Import hash: ${f.imphash[0] ?? "none"} → ${f.imphash[1] ?? "none"}` });
  if (fileLines.length) out.push({ heading: "File contents", lines: fileLines });
  const changes = changesOf(d, manual);
  if (changes.length) {
    const name = (c: (typeof changes)[number], side: "a" | "b") => {
      const at = addressOf(c.target, side);
      if (at === null) return "";
      const t = c.target;
      const n = t.kind === "match" ? (side === "a" ? t.m.a_name : t.m.b_name) : t.f.name;
      return n ? `${n} (${hex(at)})` : hex(at);
    };
    out.push({
      heading: `Changed functions (${changes.length})`,
      lines: changes.length > MAX_CHANGES ? [{ text: `Showing the ${MAX_CHANGES} most notable of ${changes.length}.` }] : [],
      table: { head: ["Status", "In A", "In B", "What changed"], rows: changes.slice(0, MAX_CHANGES).map((c) => [c.status, name(c, "a"), name(c, "b"), c.reason]) },
    });
  }
  if (manual.length) out.push({ heading: "Pairs made by hand", lines: manual.map((m) => ({ text: `${m.a_name ?? hex(m.a_addr)} (${hex(m.a_addr)}) ↔ ${m.b_name ?? hex(m.b_addr)} (${hex(m.b_addr)})` })) });
  return out;
}

export const compareMarkdown = (d: DiffDocument, manual: FunctionMatch[] = []) => markdownOf(TITLE(d), blocks(d, manual), NOTE);
export const compareHtml = (d: DiffDocument, manual: FunctionMatch[] = []) => htmlOf(TITLE(d), blocks(d, manual), NOTE);
/** The engine's document, plus the pairs made by hand and the ranked changes as the reader saw them. */
export const compareJson = (d: DiffDocument, manual: FunctionMatch[] = []) =>
  JSON.stringify({
    generator: "binfera", ...d,
    manual_pairs: manual.map((m) => ({ a: m.a_addr, b: m.b_addr })),
    changes: changesOf(d, manual).map((c) => ({ status: c.status, a: addressOf(c.target, "a"), b: addressOf(c.target, "b"), reason: c.reason })),
  }, null, 2);

/** File name stem for the saved report. */
export const compareFileStem = (d: DiffDocument) => `${d.inputs[0].name}-vs-${d.inputs[1].name}`.replace(/[^\w.-]+/g, "_");
